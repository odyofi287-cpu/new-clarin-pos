function sqlite(t, source) {
  const db = new Database(":memory:"); t.after(() => db.close());
  db.exec(readFileSync(new URL("./schema.sql", import.meta.url), "utf8").replaceAll("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT"));
  db.pragma("foreign_keys = ON");
  for (const table of ["roles","vendors","users","products","sales","sale_items","deliveries","delivery_items","vendor_returns","inventory_movements"]) {
    for (const row of source[table]) {
      const fields = Object.keys(row);
      db.prepare(`INSERT INTO ${table} (${fields.join(",")}) VALUES (${fields.map(() => "?").join(",")})`).run(...Object.values(row));
    }
  }
  return db;
}

async function api(t, db) {
  const app = express();
  app.use((req,res,next) => {req.db=db;req.user={role:req.headers["x-role"] || "STAFF",user_id:req.headers["x-user"] === "missing" ? undefined : Number(req.headers["x-user"] || 3)};next();});
  app.use("/dashboard",dashboard); app.use("/reports",reports);
  const server=app.listen(0); t.after(() => new Promise((resolve) => server.close(resolve)));
  return async (route, role="STAFF", id=3) => {
    const response=await fetch(`http://127.0.0.1:${server.address().port}${route}`,{headers:{"x-role":role,"x-user":String(id)}});
    return {status:response.status,cache:response.headers.get("cache-control"),body:response.headers.get("content-type")?.includes("json") ? await response.json() : await response.text()};
  };
}

function assertFormula(total) {
  assert.equal(total.capital,total.base_cost);
  assert.equal(total.gross_profit,Math.round((total.known_revenue-total.capital)*100)/100);
  assert.equal(total.capital,Math.round((total.recorded_capital+total.delivery_capital+total.return_capital)*100)/100);
  assert.equal(total.net_quantity,total.recorded_quantity+total.delivered_quantity-total.returned_quantity);
}

