test("return-only periods show a capital reversal; fully returned deliveries net to zero, including zero base costs",() => {
  const returned={kind:"return",quantity:2,revenue:-40,known_revenue:-40,base_cost:-20};
  const negative=summarizeProfit([returned]); assertFormula(negative);
  assert.equal(negative.capital,-20); assert.equal(negative.gross_profit,-20); assert.equal(negative.net_quantity,-2);
  const full=summarizeProfit([{kind:"delivery",quantity:2,revenue:40,known_revenue:40,base_cost:20},returned]);
  assertFormula(full); assert.equal(full.capital,0); assert.equal(full.gross_profit,0); assert.equal(full.net_quantity,0);
  const free=summarizeProfit([{kind:"recorded",quantity:2,revenue:10,known_revenue:10,base_cost:0}]);
  assertFormula(free); assert.equal(free.capital,0); assert.equal(free.gross_profit,10);
});

