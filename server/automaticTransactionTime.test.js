import test from "node:test";
import assert from "node:assert/strict";
import express from "express";
import Database from "better-sqlite3";
import { readFileSync } from "node:fs";
import { getBusinessTimestamp } from "./businessDate.js";

process.env.NODE_ENV = "test";
const { initDb } = await import("./db.js");
const { default: sales } = await import("./routes/sales.js");
const { default: deliveries } = await import("./routes/deliveries.js");
const { default: dashboard } = await import("./routes/dashboard.js");
const instant = "2026-12-31T16:00:30.000Z";
const fixed = { date: "2027-01-01", time: "00:00", created_at: instant };

function fixture() {
  const db = initDb();
  db.products = [{ id: 1, name: "Automatic drink", base_price: 10, legacy_base_price: 10, selling_price: 25, current_stock: 100, active: 1 }];
  db.sales = []; db.sale_items = []; db.deliveries = []; db.delivery_items = []; db.vendor_returns = []; db.inventory_movements = [];
  return db;
}

function sqliteFixture(t, seed) {
  const db = new Database(":memory:"); t.after(() => db.close());
  db.exec(readFileSync(new URL("./schema.sql", import.meta.url), "utf8").replaceAll("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT"));
  db.pragma("foreign_keys = ON");
  for (const table of ["roles", "vendors", "users", "products"]) {
    const columns = new Set(db.prepare(`PRAGMA table_info(${table})`).all().map((row) => row.name));
    for (const row of seed[table]) {
      const fields = Object.keys(row).filter((field) => columns.has(field));
      db.prepare(`INSERT INTO ${table} (${fields.join(",")}) VALUES (${fields.map(() => "?").join(",")})`).run(...fields.map((field) => row[field]));
    }
  }
  return {
    prepare: db.prepare.bind(db), exec: db.exec.bind(db),
    transaction: (fn) => async () => {
      db.exec("BEGIN");
      try { const result = await fn(); db.exec("COMMIT"); return result; }
      catch (error) { db.exec("ROLLBACK"); throw error; }
    },
  };
}

async function api(t, db) {
  const app = express(); app.use(express.json());
  app.use((req, res, next) => { req.db = db; req.user = { user_id: 3, role: "STAFF", vendor_id: null }; next(); });
  app.use("/sales", sales); app.use("/deliveries", deliveries); app.use("/dashboard", dashboard);
  const server = app.listen(0); t.after(() => new Promise((resolve) => server.close(resolve)));
  return async (route, method = "GET", body) => {
    const response = await fetch(`http://127.0.0.1:${server.address().port}${route}`, { method, headers: { "content-type": "application/json" }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json() };
  };
}

test("one server instant produces a matching Manila date, 24-hour time and UTC audit timestamp across boundaries", () => {
  for (const [utc, date, time] of [
    ["2026-11-05T15:59:59.999Z", "2026-11-05", "23:59"],
    ["2026-11-05T16:00:00.000Z", "2026-11-06", "00:00"],
    [instant, "2027-01-01", "00:00"],
    ["2024-02-28T16:00:00.000Z", "2024-02-29", "00:00"],
  ]) assert.deepEqual(getBusinessTimestamp(new Date(utc)), { date, time, created_at: utc });
});

for (const backend of ["memory", "SQLite"]) {
  test(`${backend}: sales and deliveries ignore missing, forged and malformed client timestamps`, async (t) => {
    t.mock.timers.enable({ apis: ["Date"], now: new Date(instant) });
    const seed = fixture(); const db = backend === "memory" ? seed : sqliteFixture(t, seed); const request = await api(t, db);
    const clientValues = [{}, { pickup_datetime: "2000-01-01T01:01", delivery_date: "2000-01-01", delivery_time: "01:01", sale_date: "2000-01-01", sale_time: "01:01", created_at: "2000-01-01T01:01:00Z" },
      { pickup_datetime: { invalid: true }, delivery_date: "2099-12-31", delivery_time: "invalid", sale_date: ["2099-12-31"], sale_time: "invalid", created_at: "2099-12-31T23:59:59Z" }];
    for (const forged of clientValues) {
      const pickup = await request("/deliveries", "POST", { vendor_id: 1, items: [{ product_id: 1, quantity: 1 }], ...forged });
      assert.equal(pickup.status, 201);
      assert.equal(pickup.body.data.delivery_date, fixed.date); assert.equal(pickup.body.data.delivery_time, fixed.time); assert.equal(pickup.body.data.created_at, instant);
      const sale = await request("/sales", "POST", { items: [{ product_id: 1, quantity: 1 }], ...forged });
      assert.equal(sale.status, 201);
      assert.equal(sale.body.data.sale_date, fixed.date); assert.equal(sale.body.data.sale_time, fixed.time); assert.equal(sale.body.data.created_at, instant);
    }
    const savedSales = backend === "memory" ? db.sales : db.prepare("SELECT * FROM sales").all();
    const savedDeliveries = backend === "memory" ? db.deliveries : db.prepare("SELECT * FROM deliveries").all();
    assert.ok(savedSales.every((row) => row.sale_date === fixed.date && row.created_at === instant));
    assert.ok(savedDeliveries.every((row) => row.delivery_date === fixed.date && row.delivery_time === fixed.time && row.created_at === instant));
    const history = await request("/sales");
    assert.equal(history.status, 200); assert.ok(history.body.data.every((row) => row.sale_time === fixed.time && row.created_at === instant));
    const stock = backend === "memory" ? db.products[0].current_stock : db.prepare("SELECT current_stock FROM products WHERE id = 1").get().current_stock;
    assert.equal(stock, 94);
    const stats = (await request("/dashboard")).body.data;
    assert.equal(stats.calculated_todays_sales, 150); assert.equal(stats.todays_transaction_count, 6);
  });

  test(`${backend}: delivery editing preserves the original date, time and audit timestamp, even for old or untimed records`, async (t) => {
    t.mock.timers.enable({ apis: ["Date"], now: new Date(instant) });
    const seed = fixture(); const db = backend === "memory" ? seed : sqliteFixture(t, seed); const request = await api(t, db);
    for (const originalTime of ["07:10", null]) {
      const response = await request("/deliveries", "POST", { vendor_id: 1, items: [{ product_id: 1, quantity: 1 }] });
      const id = response.body.data.id;
      const originalCreated = "2024-02-28T23:10:00.000Z";
      if (backend === "memory") Object.assign(db.deliveries.find((row) => row.id === id), { delivery_date: "2024-02-29", delivery_time: originalTime, created_at: originalCreated });
      else db.prepare("UPDATE deliveries SET delivery_date = ?, delivery_time = ?, created_at = ? WHERE id = ?").run("2024-02-29", originalTime, originalCreated, id);
      const changed = await request(`/deliveries/${id}`, "PUT", { delivery_date: "2099-01-01", delivery_time: "23:59", pickup_datetime: "2099-01-01T23:59", created_at: instant, payment_status: "PAID", items: [{ product_id: 1, quantity: 2 }] });
      assert.equal(changed.status, 200);
      const saved = backend === "memory" ? db.deliveries.find((row) => row.id === id) : db.prepare("SELECT * FROM deliveries WHERE id = ?").get(id);
      assert.equal(saved.delivery_date, "2024-02-29"); assert.equal(saved.delivery_time, originalTime); assert.equal(saved.created_at, originalCreated);
      assert.equal(changed.body.data.total_amount, 50); assert.equal(changed.body.data.payment_status, "PAID");
    }
  });
}

test("date and time are captured at saving, not at form opening or before stock locks cross midnight", async (t) => {
  t.mock.timers.enable({ apis: ["Date"], now: new Date("2026-11-05T15:59:59.000Z") });
  const db = fixture(); const prepare = db.prepare.bind(db);
  db.prepare = (sql) => {
    const statement = prepare(sql);
    if (/FROM products/i.test(sql) && !/current_stock/i.test(sql)) {
      const get = statement.get.bind(statement);
      statement.get = (...args) => { t.mock.timers.tick(2000); return get(...args); };
    }
    return statement;
  };
  const request = await api(t, db);
  const sale = await request("/sales", "POST", { items: [{ product_id: 1, quantity: 1 }] });
  assert.equal(sale.status, 201); assert.equal(sale.body.data.sale_date, "2026-11-06"); assert.equal(sale.body.data.sale_time, "00:00");
  t.mock.timers.setTime(Date.parse("2026-11-05T15:59:59.000Z"));
  const pickup = await request("/deliveries", "POST", { vendor_id: 1, items: [{ product_id: 1, quantity: 1 }] });
  assert.equal(pickup.status, 201); assert.equal(pickup.body.data.delivery_date, "2026-11-06"); assert.equal(pickup.body.data.delivery_time, "00:00");
});

test("legacy SQLite UTC timestamps display in Manila, missing or malformed times are not fabricated", async (t) => {
  const db = fixture();
  db.sales = [{ id: 1, user_id: 3, sale_date: "2026-11-06", created_at: "2026-11-05 16:05:00" }, { id: 2, user_id: 3, sale_date: "2026-11-06" }, { id: 3, user_id: 3, sale_date: "2026-11-06", created_at: "invalid" }];
  const request = await api(t, db); const response = await request("/sales");
  assert.equal(response.status, 200);
  assert.equal(response.body.data.find((row) => row.id === 1).sale_time, "00:05");
  assert.equal(response.body.data.find((row) => row.id === 2).sale_time, null);
  assert.equal(response.body.data.find((row) => row.id === 3).sale_time, null);
});

test("Postgres inserts bind server-owned timestamps using the existing schema, without a migration", async (t) => {
  t.mock.timers.enable({ apis: ["Date"], now: new Date(instant) });
  const calls = [];
  const db = { pool: {}, client: () => ({ query: async (sql, params) => {
    calls.push({ sql, params });
    if (/SELECT .*FROM products/i.test(sql)) return { rows: [{ id: 1, name: "Drink", current_stock: 100, active: 1, selling_price: 25, base_price: 10 }] };
    return { rows: [{ id: 1 }], rowCount: 1 };
  } }) };
  const request = await api(t, db);
  assert.equal((await request("/sales", "POST", { items: [{ product_id: 1, quantity: 1 }], sale_date: "2000-01-01" })).status, 201);
  assert.equal((await request("/deliveries", "POST", { vendor_id: 1, items: [{ product_id: 1, quantity: 1 }], pickup_datetime: "2000-01-01T10:00" })).status, 201);
  assert.deepEqual(calls.find((call) => call.sql.startsWith("INSERT INTO sales (")).params, [fixed.date, 25, 3, instant]);
  assert.deepEqual(calls.find((call) => call.sql.startsWith("INSERT INTO deliveries (")).params, [1, fixed.date, fixed.time, 25, 3, instant]);
  assert.ok(calls.every((call) => !/ALTER|CREATE TABLE/.test(call.sql)));
});
