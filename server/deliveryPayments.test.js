function sqlite(t, source) {
  const db = new Database(":memory:"); t.after(() => db.close());
  db.exec(readFileSync(new URL("./schema.sql", import.meta.url), "utf8").replaceAll("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT"));
  db.pragma("foreign_keys = ON");
  for (const table of ["roles","vendors","users","products","sales","sale_items","deliveries","delivery_items","vendor_returns","inventory_movements"]) {
    for (const row of source[table]) {
      const fields = Object.keys(row);
      db.prepare(`INSERT INTO ${table} (${fields.join(",")}) VALUES (${fields.map(() => "?").join(",")})`).run(...Object.values(row));
    }
  }
  db.transaction = (fn) => async () => { db.exec("BEGIN"); try { const result = await fn(); db.exec("COMMIT"); return result; } catch(error) { db.exec("ROLLBACK"); throw error; } };
  return db;
}

async function api(t, db) {
  const app = express(); app.use(express.json());
  app.use((req,res,next) => { req.db=db; req.user={ role:req.headers["x-role"] || "STAFF", user_id:3, vendor_id:1 }; next(); });
  app.use("/deliveries",deliveries); app.use("/returns",returns); app.use("/dashboard",dashboard);
  const server=app.listen(0); t.after(() => new Promise((resolve) => server.close(resolve)));
  return async (route,method="GET",body,role="STAFF") => {
    const response=await fetch(`http://127.0.0.1:${server.address().port}${route}`,{ method,headers:{ "content-type":"application/json","x-role":role },...(body ? {body:JSON.stringify(body)} : {}) });
    return { status:response.status,body:await response.json() };
  };
}

test("fully returned is based on every delivered product, including duplicate lines and zero-price items", () => {
  const deliveries=[{ id:1,total_amount:10,payment_status:"UNPAID" },{ id:2,total_amount:0,payment_status:"UNPAID" },{ id:3,total_amount:10,payment_status:"PAID" },{ id:4,total_amount:0,payment_status:"UNPAID" }];
  const items=[{ delivery_id:1,product_id:1,quantity:1 },{ delivery_id:1,product_id:1,quantity:2 },{ delivery_id:1,product_id:2,quantity:1 },{ delivery_id:2,product_id:1,quantity:2 },{ delivery_id:3,product_id:1,quantity:1 }];
  const returns=[{ delivery_id:1,product_id:1,quantity:3,total_product_price_returned:10 },{ delivery_id:2,product_id:1,quantity:1,total_product_price_returned:0 },{ delivery_id:3,product_id:1,quantity:1,total_product_price_returned:10 },{ delivery_id:null,product_id:2,quantity:100,total_product_price_returned:0 }];
  const snapshot=JSON.stringify({deliveries,items,returns});
  let rows=buildDeliveryPaymentAccounts(deliveries,returns,items);
  assert.deepEqual(rows.map((r) => r.payment_status),["UNPAID","UNPAID","PAID","UNPAID"],"Zero balance alone does not prove a complete return; unlinked returns cannot settle deliveries");
  assert.equal(JSON.stringify({deliveries,items,returns}),snapshot,"Calculation is read-only");
  returns.push({delivery_id:1,product_id:2,quantity:1,total_product_price_returned:0},{delivery_id:2,product_id:1,quantity:1,total_product_price_returned:0});
  rows=buildDeliveryPaymentAccounts(deliveries,returns,items);
  assert.deepEqual(rows.map((r) => r.payment_status),["FULLY_RETURNED","FULLY_RETURNED","PAID","UNPAID"]);
  assert.equal(rows[0].recorded_payment_status,"UNPAID"); assert.equal(rows[0].amount_due,0);
  assert.equal(rows[2].fully_returned,false,"A historical paid delivery remains paid");
});

