    const record=(items) => request("/returns","POST",{vendor_id:1,delivery_id:1,return_date:today,return_time:"11:00",items});
    assert.equal((await record([{product_id:1,quantity:2},{product_id:2,quantity:1}])).status,201);
    let delivery=(await request("/deliveries/1")).body.data;
    assert.equal(delivery.payment_status,"UNPAID"); assert.equal(delivery.amount_due,95);
    assert.equal((await record([{product_id:1,quantity:2},{product_id:2,quantity:1}])).status,201);
    delivery=(await request("/deliveries/1")).body.data;
    assert.equal(delivery.payment_status,"FULLY_RETURNED"); assert.equal(delivery.recorded_payment_status,"UNPAID"); assert.equal(delivery.amount_due,0);
    assert.equal(delivery.return_deduction,190);
    const list=(await request("/deliveries")).body.data;
    assert.equal(list.find((r) => r.id===1).payment_status,"FULLY_RETURNED");
    assert.equal(list.find((r) => r.id===2).payment_status,"PAID");
    assert.ok(!list.some((r) => r.id===4),"Staff ownership remains enforced");
    const eligible=(await request("/returns/eligible-deliveries?vendor_id=1")).body.data;
    assert.equal(eligible.find((r) => r.id===1).payment_status,"FULLY_RETURNED"); assert.equal(eligible.find((r) => r.id===1).returnable,false);
    const summary=(await request("/dashboard","GET",null,"VENDOR")).body.data.vendor_summary;
    assert.equal(summary.payment_summary.fully_returned_delivery_count,2); assert.equal(summary.payment_summary.unpaid_delivery_count,1);
    assert.equal(summary.payment_summary.paid_delivery_count,1); assert.equal(summary.payment_summary.net_payable_amount,0);
    assert.equal(summary.today_delivery_accounts.find((r) => r.id===1).payment_status,"FULLY_RETURNED");
    assert.equal(summary.daily_history.find((day) => day.account_date===today).fully_returned_delivery_count,2);
