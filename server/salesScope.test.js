function sqliteFixture(t, seed) {
  const db = new Database(":memory:"); t.after(() => db.close());
  db.exec(readFileSync(new URL("./schema.sql", import.meta.url), "utf8").replaceAll("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT"));
  db.pragma("foreign_keys = ON");
  for (const table of ["roles", "vendors", "users", "products", "sales", "sale_items", "deliveries", "delivery_items", "vendor_returns"]) {
    for (const row of seed[table]) {
      const fields = Object.keys(row);
      db.prepare(`INSERT INTO ${table} (${fields.join(",")}) VALUES (${fields.map(() => "?").join(",")})`).run(...Object.values(row));
    }
  }
  return db;
}

async function api(t, db, signed = false) {
  const app = express();
  app.use((req, res, next) => { req.db = db; if (!signed) req.user = { role: req.headers["x-role"] || "STAFF", user_id: req.headers["x-user"] === "missing" ? undefined : Number(req.headers["x-user"] || 3), vendor_id: 1 }; next(); });
  if (signed) app.use(authMiddleware);
  app.use("/dashboard", dashboard); app.use("/reports", reports);
  const server = app.listen(0); t.after(() => new Promise((resolve) => server.close(resolve)));
  return async (route, role = "STAFF", id = 3) => {
    const headers = signed ? { Authorization: `Bearer ${jwt.sign({ user_id: id, role }, process.env.JWT_SECRET || "change-this-secret")}` } : { "x-role": role, "x-user": String(id) };
    const response = await fetch(`http://127.0.0.1:${server.address().port}${route}`, { headers });
    const text = await response.text();
    return { status: response.status, cache: response.headers.get("cache-control"), body: response.headers.get("content-type")?.includes("json") ? JSON.parse(text) : text };
  };
}
